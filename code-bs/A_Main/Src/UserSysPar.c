/****************************************************************************************************************/
void SysParHandle(void)
{
	u16 Sts = 0;
	/*****************************************************************************************************/
	//
	//Sts = gSysParLoadAll();

	gSysParInitAll(EPROM_INIT_CMD_ALL);

	if (Sts == SYSPAR_OK)
	{
		gSysErr.ErrHd.bit.EPROMError = FALSE;
	} else if (Sts == SYSPAR_CHECK_ERR)
	{
		gSysErr.ErrCtl.bit.SysParErr = TRUE;
	} else {
		gSysErr.ErrHd.bit.EPROMError = TRUE;
	}
	/*****************************************************************************************************/

	/*****************************************************************************************************/
	//
	SysParP8.SVER = SW_VERSION;
	SysParP6.SAVE = 0;
	SysParP4.CSPD = 0;
	SysParP5.CTOR = 0;

	/*****************************************************************************************************/

	/*****************************************************************************************************/
	gMotoParSec();
	/*****************************************************************************************************/

	/*****************************************************************************************************/
	//
	if (SysParP8.MTYPE != SysParP8.MTBK)
	{
		SysParP0.MSPD = MotoPar.MSPD;
		SysParP0.MTOR = MotoPar.MTOR * 1000.0f / MotoPar.NTOR;
		SysParP8.MTBK = SysParP8.MTYPE;
		SysParP6.SAVE = 1;
	}
	/*****************************************************************************************************/
}
