/****************************************************************************************************************/
u16 gSysParLoadAll(void)
{
	u16 sts = 0;

	sts = gSysParPartRead(&SysParP0.CTL,	SYSPAR_P0_ADS,	sizeof_16(MC_SYS_PAR_P0));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP1.INUM,		SYSPAR_P1_ADS,	sizeof_16(MC_SYS_PAR_P1));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP2.ONUM,		SYSPAR_P2_ADS,	sizeof_16(MC_SYS_PAR_P2));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP3.PAS,		SYSPAR_P3_ADS,	sizeof_16(MC_SYS_PAR_P3));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP4.SAS,		SYSPAR_P4_ADS,	sizeof_16(MC_SYS_PAR_P4));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP5.TAS,		SYSPAR_P5_ADS,	sizeof_16(MC_SYS_PAR_P5));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}

	sts = gSysParPartRead(&SysParP6.ADR,		SYSPAR_P6_ADS,	sizeof_16(MC_SYS_PAR_P6));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}
	sts = gSysParPartRead(&SysParP7.PDEV,		SYSPAR_P7_ADS,	sizeof_16(MC_SYS_PAR_P7));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}

	sts = gSysParPartRead(&SysParP8.SVER,		SYSPAR_P8_ADS,	sizeof_16(MC_SYS_PAR_P8));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}

	sts = gSysParPartRead(&SysParP9.Index,		SYSPAR_P9_ADS,	sizeof_16(MC_SYS_PAR_P9));
	if (sts != SYSPAR_OK) {gSysParInitAll(EPROM_INIT_CMD_ALL);	goto SAVE_LOOP;}



	if ((SysParP9.Index != EROM_INIT) || (SysParP8.INIT == EPROM_INIT_CMD_ALL)) //
	{
		gSysParInitAll(EPROM_INIT_CMD_ALL);
		goto SAVE_LOOP;
	}

	if ((SysParP8.INIT == EPROM_INIT_CMD_L1) || (SysParP8.SVER != SW_VERSION)) //
	{
		SysParP8.SVER = SW_VERSION;
		gSysParInitAll(EPROM_INIT_CMD_L1);
		goto SAVE_LOOP;
	}

	sts = gSysParCheckAll();
	if (sts != SYSPAR_OK) {
		gSysParInitAll(EPROM_INIT_CMD_L1);
		goto SAVE_LOOP;
	} else {
		goto END_LOOP;
	}
SAVE_LOOP:
	gSysParPartWrite(&SysParP0.CTL,	SYSPAR_P0_ADS,	sizeof_16(MC_SYS_PAR_P0));
	gSysParPartWrite(&SysParP1.INUM,	 	SYSPAR_P1_ADS,	sizeof_16(MC_SYS_PAR_P1));
	gSysParPartWrite(&SysParP2.ONUM,	SYSPAR_P2_ADS,	sizeof_16(MC_SYS_PAR_P2));
	gSysParPartWrite(&SysParP3.PAS,	SYSPAR_P3_ADS,	sizeof_16(MC_SYS_PAR_P3));
	gSysParPartWrite(&SysParP4.SAS,		SYSPAR_P4_ADS,	sizeof_16(MC_SYS_PAR_P4));
	gSysParPartWrite(&SysParP5.TAS,		SYSPAR_P5_ADS,	sizeof_16(MC_SYS_PAR_P5));

	gSysParPartWrite(&SysParP6.ADR,		SYSPAR_P6_ADS,	sizeof_16(MC_SYS_PAR_P6));
	gSysParPartWrite(&SysParP7.PDEV,		SYSPAR_P7_ADS,	sizeof_16(MC_SYS_PAR_P7));
	gSysParPartWrite(&SysParP8.SVER,		SYSPAR_P8_ADS,	sizeof_16(MC_SYS_PAR_P8));
	gSysParPartWrite(&SysParP9.Index,		SYSPAR_P9_ADS,	sizeof_16(MC_SYS_PAR_P9));


END_LOOP:
	return sts;
}
